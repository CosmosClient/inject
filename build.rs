//! Assembles the macOS injection shellcode (`shellcode/<arch>.s`) and writes
//! it to `$OUT_DIR/shellcode.rs` as byte arrays, which `src/mac.rs` includes.
//!
//! Both architectures are assembled whenever the target OS is macOS, so the
//! byte-for-byte test (`mac::tests::shellcode_matches_reference`) can check
//! both from one host. The shellcode is only compiled into the crate for the
//! target architecture (`SHELLCODE`).

use std::{
    env,
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
    process::Command,
};

use object::{Object, ObjectSection};

fn main() {
    println!("cargo:rerun-if-changed=shellcode/aarch64.s");
    println!("cargo:rerun-if-changed=shellcode/x86_64.s");

    // `src/mac.rs`, the only user of the shellcode, is macOS-only. Nothing to
    // generate for other targets, and a cross host may not assemble Mach-O.
    if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("macos") {
        return;
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let aarch64 = assemble("arm64", "shellcode/aarch64.s", &out_dir);
    let x86_64 = assemble("x86_64", "shellcode/x86_64.s", &out_dir);

    let mut rs = String::from("// @generated by build.rs from shellcode/*.s — do not edit.\n");
    emit_const(&mut rs, "SHELLCODE_AARCH64", &aarch64);
    emit_const(&mut rs, "SHELLCODE_X86_64", &x86_64);
    rs.push_str("#[cfg(target_arch = \"aarch64\")]\npub(crate) const SHELLCODE: &[u8] = SHELLCODE_AARCH64;\n");
    rs.push_str("#[cfg(target_arch = \"x86_64\")]\npub(crate) const SHELLCODE: &[u8] = SHELLCODE_X86_64;\n");
    fs::write(out_dir.join("shellcode.rs"), rs).unwrap();
}

/// Assembles `src` for `arch` with the C toolchain and returns its `__text`
/// bytes, which are the shellcode.
fn assemble(arch: &str, src: &str, out_dir: &Path) -> Vec<u8> {
    let cc = env::var("CC").unwrap_or_else(|_| "cc".into());
    let obj = out_dir.join(format!("shellcode_{arch}.o"));
    let status = Command::new(&cc)
        .args(["-arch", arch, "-c", src, "-o"])
        .arg(&obj)
        .status()
        .unwrap_or_else(|e| panic!("failed to run `{cc}` to assemble {src}: {e}"));
    assert!(status.success(), "assembling {src} for {arch} failed");

    let data = fs::read(&obj).unwrap();
    let file = object::File::parse(&*data).expect("parse assembled object");
    let text = file
        .section_by_name("__text")
        .expect("assembled object has a __text section");
    text.data().expect("read __text section").to_vec()
}

fn emit_const(rs: &mut String, name: &str, bytes: &[u8]) {
    // The architecture that isn't the target's is only used by the test.
    write!(rs, "#[allow(dead_code)]\npub(crate) const {name}: &[u8] = &[").unwrap();
    for b in bytes {
        write!(rs, "{b},").unwrap();
    }
    rs.push_str("];\n");
}
